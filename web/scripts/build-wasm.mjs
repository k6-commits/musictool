// Compiles wasm/swiftf0-kernel.ts (AssemblyScript) and embeds the module in src/dsp/swiftf0/kernel.ts.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'e2e/out/swiftf0-kernel.wasm');
mkdirSync(dirname(out), { recursive: true });
execFileSync(
  process.execPath,
  [join(root, 'node_modules/assemblyscript/bin/asc.js'), join(root, 'wasm/swiftf0-kernel.ts'), '-O3', '--runtime', 'stub', '--noAssert', '--enable', 'simd', '--outFile', out],
  { stdio: 'inherit' },
);
const bytes = readFileSync(out);
// Kept under 4 KiB so that browsers allow compiling it synchronously on the main thread.
if (bytes.length > 4096) throw new Error(`kernel is ${bytes.length} bytes; model.ts compiles it synchronously, keep it under 4 KiB`);
writeFileSync(
  join(root, 'src/dsp/swiftf0/kernel.ts'),
  `// Generated by scripts/build-wasm.mjs from wasm/swiftf0-kernel.ts (AssemblyScript). Do not edit.\n` +
    `/** The SwiftF0 convolution kernel as WebAssembly (SIMD), base64. */\nexport const KERNEL_WASM =\n  '${bytes.toString('base64')}';\n`,
);
console.log(`src/dsp/swiftf0/kernel.ts: ${bytes.length} bytes of WebAssembly`);
