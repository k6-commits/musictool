"""Generates src/dsp/swiftf0/weights.ts from the SwiftF0 ONNX model (swift-f0 on PyPI, MIT License).

    pip install onnx numpy swift-f0==0.3.0
    python scripts/export-swiftf0.py [path/to/model.onnx]

Writes the network's weights (BatchNorm already folded in by the export), the STFT windows and the sparse
log-frequency filters as base64 float32, in the order src/dsp/swiftf0/model.ts runs them. (The pitch-bin centers
are a geometric series that model.ts computes; the script checks that they still are.)
"""
import base64
import hashlib
import os
import sys

import numpy as np
import onnx
from onnx import numpy_helper

here = os.path.dirname(os.path.abspath(__file__))
if len(sys.argv) > 1:
    path = sys.argv[1]
else:
    import swift_f0
    path = os.path.join(os.path.dirname(swift_f0.__file__), "model.onnx")
model = onnx.load(path)
graph = model.graph
init = {t.name: numpy_helper.to_array(t) for t in graph.initializer}
digest = hashlib.sha256(open(path, "rb").read()).hexdigest()


def b64(array):
    return base64.b64encode(np.ascontiguousarray(array, dtype="<f4").tobytes()).decode("ascii")


convs = []
for node in graph.node:
    if node.op_type != "Conv":
        continue
    attrs = {a.name: (list(a.ints) if a.ints else a.i) for a in node.attribute}
    weight, bias = init[node.input[1]], init[node.input[2]]
    convs.append({"shape": list(weight.shape), "dilation": attrs["dilations"], "pads": attrs["pads"],
                  "w": b64(weight), "b": b64(bias)})
assert len(convs) == 18, len(convs)

# STFT windows (1024, 2048, 512: the model's channel order) and the log-frequency filters, stored sparse in the
# graph as ScatterElements into a (bins x 128) matrix; each filter covers a contiguous run of STFT bins.
windows = [init[n.input[1]] for n in graph.node if n.op_type == "Mul" and n.input[1] in init and init[n.input[1]].shape in [(1024,), (2048,), (512,)]]
assert [w.shape[0] for w in windows] == [1024, 2048, 512], [w.shape for w in windows]
filters = []
scatter = [n for n in graph.node if n.op_type == "ScatterElements"]
for size, node in zip((1024, 2048, 512), scatter):
    indices, values = init[node.input[1]].astype(np.int64), init[node.input[2]]
    n_lin = size // 2 + 1
    n_log = 128
    dense = np.zeros(n_lin * n_log, np.float32)
    dense[indices] = values
    dense = dense.reshape(n_lin, n_log).T  # (log bin, STFT bin)
    starts, lengths, weights = [], [], []
    for row in dense:
        nz = np.flatnonzero(row)
        lo, hi = (int(nz[0]), int(nz[-1]) + 1) if len(nz) else (0, 0)
        starts.append(lo)
        lengths.append(hi - lo)
        weights.append(row[lo:hi])
    filters.append({"starts": starts, "lengths": lengths, "w": b64(np.concatenate(weights))})
# The 95 pitch-bin centers are float32 geomspace(46.875, 2093.75, 95); model.ts derives them, check that it may.
centers = [init[n.input[0]] for n in graph.node if n.op_type == "GreaterOrEqual"][0]
derived = (46.875 * (2093.75 / 46.875) ** (np.arange(95) / 94)).astype(np.float32)
assert np.array_equal(centers, derived), "pitch-bin centers are not the expected geometric series"

out = os.path.join(here, "..", "src", "dsp", "swiftf0", "weights.ts")
with open(out, "w") as f:
    f.write("/*! SwiftF0 model weights, from swift-f0 0.3.0 (https://github.com/lars76/swift-f0).\n")
    f.write(" * Copyright (c) 2025-2026 Lars Nieradzik. MIT License: permission is hereby granted, free of charge,\n")
    f.write(" * to any person obtaining a copy of this software and associated documentation files (the \"Software\"),\n")
    f.write(" * to deal in the Software without restriction, including without limitation the rights to use, copy,\n")
    f.write(" * modify, merge, publish, distribute, sublicense, and/or sell copies of the Software, and to permit\n")
    f.write(" * persons to whom the Software is furnished to do so, subject to the following conditions: The above\n")
    f.write(" * copyright notice and this permission notice shall be included in all copies or substantial portions\n")
    f.write(" * of the Software. THE SOFTWARE IS PROVIDED \"AS IS\", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED,\n")
    f.write(" * INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND\n")
    f.write(" * NONINFRINGEMENT. IN NO EVENT SHALL THE AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR\n")
    f.write(" * OTHER LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN\n")
    f.write(" * CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE.\n */\n")
    f.write(f"// Generated by scripts/export-swiftf0.py from model.onnx (sha256 {digest}). Do not edit.\n\n")
    f.write("export interface ConvData {\n  shape: number[];\n  dilation: number[];\n  pads: number[];\n  w: string;\n  b: string;\n}\n\n")
    f.write("export const CONVS: ConvData[] = [\n")
    for c in convs:
        f.write(f"  {{ shape: {c['shape']}, dilation: {c['dilation']}, pads: {c['pads']}, w: '{c['w']}', b: '{c['b']}' }},\n")
    f.write("];\n\n")
    f.write("/** Hann windows for the 1024-, 2048- and 512-point STFTs (base64 float32). */\n")
    f.write("export const WINDOWS: string[] = [\n")
    for w in windows:
        f.write(f"  '{b64(w)}',\n")
    f.write("];\n\n")
    f.write("/** Log-frequency filters per STFT: for each of the 128 bands, the first STFT bin, the run length and the weights. */\n")
    f.write("export const FILTERS: { starts: number[]; lengths: number[]; w: string }[] = [\n")
    for flt in filters:
        f.write(f"  {{ starts: {flt['starts']}, lengths: {flt['lengths']}, w: '{flt['w']}' }},\n")
    f.write("];\n")
print(f"wrote {out}: {len(convs)} convolutions, {sum(int(np.prod(c['shape'])) for c in convs)} weights")
